# ============================================================

@pdf_to_docx_bp.route(
    "/pdf-to-docx/preview/<conversion_id>",
    methods=["GET"],
)
def preview_docx(conversion_id):
    """
    Preview the generated DOCX.

    If the browser/page needs the original PDF for preview,
    this route can also return it using ?source=1.
    """

    conversion_folder = (
        find_conversion_folder(
            conversion_id
        )
    )

    if not conversion_folder:
        abort(404)

    metadata = load_metadata(
        conversion_folder
    )

    if not metadata:
        abort(404)

    expires_at = metadata.get(
        "expires_at",
        0,
    )

    try:
        if time.time() >= float(
            expires_at
        ):
            delete_conversion_folder(
                conversion_folder
            )

            abort(404)

    except (
        ValueError,
        TypeError,
    ):
        abort(404)

    # --------------------------------------------------------
    # Source PDF preview
    # --------------------------------------------------------

    if request.args.get(
        "source"
    ) == "1":

        source_pdf = (
            conversion_folder
            / "_source.pdf"
        )

        if not source_pdf.exists():
            abort(404)

        return send_file(
            source_pdf,
            mimetype="application/pdf",
            as_attachment=False,
            download_name=(
                metadata.get(
                    "original_filename",
                    "document.pdf",
                )
            ),
        )

    # --------------------------------------------------------
    # DOCX preview/download
    #
    # Browsers cannot natively display DOCX in the same way
    # they display PDF. This returns the DOCX file.
    # --------------------------------------------------------

    docx_path = (
        conversion_folder
        / metadata.get(
            "output_filename",
            "converted.docx",
        )
    )

    if not docx_path.exists():
        abort(404)

    return send_file(
        docx_path,
        mimetype=(
            "application/vnd.openxmlformats-officedocument."
            "wordprocessingml.document"
        ),
        as_attachment=False,
        download_name=metadata.get(
            "output_filename",
            "converted.docx",
        ),
    )


