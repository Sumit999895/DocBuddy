def get_conversion_history():
    """
    Return temporary conversion history.

    No database is used.
    No permanent history is used.
    """

    cleanup_expired_files()

    user_folder = get_user_folder()

    if not user_folder.exists():
        return []

    history = []

    current_time = time.time()

    for conversion_folder in user_folder.iterdir():

        if not conversion_folder.is_dir():
            continue

        metadata = load_metadata(
            conversion_folder
        )

        if not metadata:
            continue

        expires_at = metadata.get(
            "expires_at",
            0,
        )

        try:
            expires_at = float(
                expires_at
            )

        except (
            ValueError,
            TypeError,
        ):
            continue

        # Do not show expired files.
        if current_time >= expires_at:
            continue

        conversion_id = metadata.get(
            "id"
        )

        if not conversion_id:
            continue

        docx_path = (
            conversion_folder
            / metadata.get(
                "output_filename",
                "converted.docx",
            )
        )

        if not docx_path.exists():
            continue

        created_at = metadata.get(
            "created_at",
            current_time,
        )

        history.append(
            {
                "id": conversion_id,
                "original_filename": metadata.get(
                    "original_filename",
                    "document.pdf",
                ),
                "output_filename": metadata.get(
                    "output_filename",
                    "converted.docx",
                ),
                "created_at": created_at,
                "created_at_display": format_timestamp(
                    created_at
                ),
                "expires_at": expires_at,
                "expires_at_display": format_timestamp(
                    expires_at
                ),
                "size": docx_path.stat().st_size,
            }
        )

    # Newest first.
    history.sort(
        key=lambda item: item.get(
            "created_at",
            0,
        ),
        reverse=True,
    )

    return history


@pdf_to_docx_bp.route(
    "/pdf-to-docx/history",
    methods=["GET"],
)
def history():
    """Return temporary conversion history as JSON."""

    return jsonify(
        get_conversion_history()
    )


