# ============================================================

@pdf_to_docx_bp.route(
    "/pdf-to-docx/download/<conversion_id>",
    methods=["GET"],
)
def download_docx(conversion_id):
    """Download temporary DOCX file."""

    conversion_folder = (
        find_conversion_folder(
            conversion_id
        )
    )

    if not conversion_folder:
        abort(404)

    metadata = load_metadata(
        conversion_folder
    )

    if not metadata:
        abort(404)

    expires_at = metadata.get(
        "expires_at",
        0,
    )

    try:
        if time.time() >= float(
            expires_at
        ):
            delete_conversion_folder(
                conversion_folder
            )

            abort(404)

    except (
        ValueError,
        TypeError,
    ):
        abort(404)

    output_filename = metadata.get(
        "output_filename",
        "converted.docx",
    )

    docx_path = (
        conversion_folder
        / output_filename
    )

    if not docx_path.exists():
        abort(404)

    original_filename = metadata.get(
        "original_filename",
        "document.pdf",
    )

    original_stem = Path(
        original_filename
    ).stem

    download_name = (
        f"{original_stem}.docx"
    )

    return send_file(
        docx_path,
        mimetype=(
            "application/vnd.openxmlformats-officedocument."
            "wordprocessingml.document"
        ),
        as_attachment=True,
        download_name=download_name,
    )


