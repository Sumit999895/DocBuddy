@pdf_to_docx_bp.route(
    "/pdf-to-docx/convert",
    methods=["POST"],
)
def convert():
    """Upload and convert PDF to DOCX."""

    # --------------------------------------------------------
    # Check uploaded file
    # --------------------------------------------------------

    pdf_file = request.files.get(
        "pdf_file"
    )

    if pdf_file is None:
        pdf_file = request.files.get(
            "file"
        )

    if pdf_file is None:
        flash(
            "Please select a PDF file.",
            "error",
        )

        return redirect(
            url_for(
                "pdf_to_docx.pdf_to_docx"
            )
        )

    if not pdf_file.filename:
        flash(
            "Please select a PDF file.",
            "error",
        )

        return redirect(
            url_for(
                "pdf_to_docx.pdf_to_docx"
            )
        )

    original_filename = secure_filename(
        pdf_file.filename
    )

    if not original_filename:
        flash(
            "Invalid filename.",
            "error",
        )

        return redirect(
            url_for(
                "pdf_to_docx.pdf_to_docx"
            )
        )

    if not allowed_file(
        original_filename
    ):
        flash(
            "Only PDF files are allowed.",
            "error",
        )

        return redirect(
            url_for(
                "pdf_to_docx.pdf_to_docx"
            )
        )

    # --------------------------------------------------------
    # Check file size
    # --------------------------------------------------------

    try:
        pdf_file.seek(
            0,
            os.SEEK_END,
        )

        file_size = pdf_file.tell()

        pdf_file.seek(
            0
        )

        if file_size > MAX_FILE_SIZE:
            flash(
                "PDF file is too large. "
                "Maximum size is 100 MB.",
                "error",
            )

            return redirect(
                url_for(
                    "pdf_to_docx.pdf_to_docx"
                )
            )

    except Exception:
        # Continue if the stream does not support size detection.
        pass

    # --------------------------------------------------------
    # Create temporary conversion folder
    # --------------------------------------------------------

    conversion_id = None
    conversion_folder = None

    try:

        conversion_id, conversion_folder = (
            create_conversion_folder()
        )

        # ----------------------------------------------------
        # Temporary source PDF
        # ----------------------------------------------------

        pdf_path = (
            conversion_folder
            / "_source.pdf"
        )

        # ----------------------------------------------------
        # Temporary DOCX output
        # ----------------------------------------------------

        docx_path = (
            conversion_folder
            / "converted.docx"
        )

        # ----------------------------------------------------
        # Save uploaded PDF
        # ----------------------------------------------------

        pdf_file.save(
            str(pdf_path)
        )

        if not pdf_path.exists():
            raise RuntimeError(
                "Uploaded PDF could not be saved."
            )

        if pdf_path.stat().st_size == 0:
            raise RuntimeError(
                "Uploaded PDF is empty."
            )

        # ----------------------------------------------------
        # Convert PDF → DOCX
        # ----------------------------------------------------

        logger.info(
            "Starting PDF→DOCX conversion: %s",
            pdf_path,
        )

        convert_pdf_to_docx(
            pdf_path,
            docx_path,
        )

        # ----------------------------------------------------
        # Verify output
        # ----------------------------------------------------

        if not docx_path.exists():
            raise RuntimeError(
                "DOCX file was not created."
            )

        if docx_path.stat().st_size == 0:
            raise RuntimeError(
                "Generated DOCX file is empty."
            )

        # ----------------------------------------------------
        # Save metadata
        # ----------------------------------------------------

        save_metadata(
            conversion_folder=conversion_folder,
            conversion_id=conversion_id,
            original_filename=original_filename,
            output_filename="converted.docx",
        )

        # ----------------------------------------------------
        # Remove source PDF?
        #
        # KEEPING IT temporarily is useful if the preview
        # page displays the original PDF.
        # It will automatically be deleted with the folder.
        # ----------------------------------------------------

        flash(
            "PDF converted to DOCX successfully.",
            "success",
        )

        return redirect(
            url_for(
                "pdf_to_docx.pdf_to_docx",
                conversion_id=conversion_id,
            )
        )

    except Exception as exc:

        logger.exception(
            "PDF→DOCX conversion failed"
        )

        # This prints the complete error in the terminal,
        # which makes debugging much easier.
        traceback.print_exc()

        # Delete failed conversion folder.
        if conversion_folder:
            delete_conversion_folder(
                conversion_folder
            )

        flash(
            f"PDF to DOCX conversion failed: {exc}",
            "error",
        )

        return redirect(
            url_for(
                "pdf_to_docx.pdf_to_docx"
            )
        )


